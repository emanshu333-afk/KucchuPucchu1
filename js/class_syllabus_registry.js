/**
 * Build Dropper Syllabus dynamically by combining both Class 11th and Class 12th
 * comprehensively across all subjects (Physics, Chemistry, Maths, Zoology, Anatomy, English, Physical Education).
 */
function buildCombinedDropperSyllabus(class11, class12) {
  const dropper = {};
  const subjectKeys = ['physics', 'chemistry', 'maths', 'zoology', 'anatomy', 'english', 'physical_education'];

  subjectKeys.forEach(function (key) {
    const s11 = class11 ? class11[key] : null;
    const s12 = class12 ? class12[key] : null;
    if (!s11 && !s12) return;

    const baseObj = s11 || s12;
    const combinedChapters = [];
    let runningNum = 1;

    // 1. Combine all Class 11 Chapters
    if (s11 && Array.isArray(s11.chapters)) {
      s11.chapters.forEach(function (ch) {
        combinedChapters.push({
          num: String(runningNum).padStart(2, '0'),
          classOrigin: 'Class 11',
          title: '[Class 11] ' + ch.title,
          topics: ch.topics || ''
        });
        runningNum++;
      });
    }

    // 2. Combine all Class 12 Chapters
    if (s12 && Array.isArray(s12.chapters)) {
      s12.chapters.forEach(function (ch) {
        combinedChapters.push({
          num: String(runningNum).padStart(2, '0'),
          classOrigin: 'Class 12',
          title: '[Class 12] ' + ch.title,
          topics: ch.topics || ''
        });
        runningNum++;
      });
    }

    dropper[key] = {
      id: baseObj.id,
      name: baseObj.name,
      icon: baseObj.icon,
      iconBg: baseObj.iconBg,
      chapters: combinedChapters
    };
  });

  return dropper;
}

CLASS_SYLLABUS_REGISTRY['dropper'] = buildCombinedDropperSyllabus(
  CLASS_SYLLABUS_REGISTRY['11th'],
  CLASS_SYLLABUS_REGISTRY['12th']
);

if (typeof window !== 'undefined') {
  window.CLASS_SYLLABUS_REGISTRY = CLASS_SYLLABUS_REGISTRY;
}
